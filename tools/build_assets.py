"""Download portfolio images from the old Webflow CDN, convert to WebP and emit assets/js/data.js."""
import json, subprocess, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT
CACHE = ROOT / "tools" / "_cache"
CDN = "https://cdn.prod.website-files.com/64ee4c358275d03e323c73e8/"
CDN_SITE = "https://cdn.prod.website-files.com/64e731a821086db3a060f0b5/"

EXTRA = {
    "me-hero": CDN_SITE + "65019b3b418687b05937a83c_IMG_1088_1200p_optimized.webp",
    "me-about": CDN_SITE + "675dbb96368a94efb462c95b_IMG_9741.avif",
    "logo-tsg": CDN_SITE + "675e1e4694482e98bc5142da_logo_tsg.avif",
    "logo-vivid": CDN_SITE + "675e1e4621bbb189b10e3ca5_logo_vivid.avif",
    "logo-revulo": CDN_SITE + "675e1ff9eb3bdb2d2d6645a1_logo_revulo.avif",
    "logo-rage": CDN_SITE + "675e1f689f940c0315505774_logo_rage.avif",
}


def fetch(url: str, name: str) -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    dst = CACHE / (name + Path(url.split("?")[0]).suffix.replace("%20", ""))
    if not dst.exists():
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        dst.write_bytes(urllib.request.urlopen(req, timeout=60).read())
    return dst


def webp(src: Path, dst: Path, width: int, q: int = 80):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        return
    vf = f"scale='min({width},iw)':-2"
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(src), "-vf", vf,
                    "-c:v", "libwebp", "-quality", str(q), "-frames:v", "1", str(dst)], check=True)


def logo(src: Path, dst: Path, size: int = 160):
    # ffmpeg drops the AVIF alpha plane, so logos go through Pillow: trim transparent padding, centre in a square
    from PIL import Image
    im = Image.open(src).convert("RGBA")
    im = im.crop(im.getchannel("A").getbbox() or (0, 0, *im.size))
    im.thumbnail((size, size), Image.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(im, ((size - im.width) // 2, (size - im.height) // 2))
    canvas.save(dst, "WEBP", quality=90, method=6)


def halves(src: Path) -> list:
    from PIL import Image
    im = Image.open(src)
    h = im.height // 2
    out = []
    for n, box in enumerate([(0, 0, im.width, h), (0, h, im.width, im.height)]):
        dst = src.with_name(f"{src.stem}-{'ab'[n]}.png")
        if not dst.exists():
            im.crop(box).save(dst)
        out.append(dst)
    return out


def tint(img: Path) -> str:
    """Signature hue of a project's key art, normalised to one lightness/saturation so every tint reads on the dark UI."""
    import colorsys
    from PIL import Image
    px = Image.open(img).convert("RGB").resize((64, 64)).getdata()
    buckets = [0.0] * 24
    for r, g, b in px:
        h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        if s > .35 and v > .3:  # ignore greys, skies washed to white, and shadows
            buckets[int(h * 24) % 24] += s * v
    if not any(buckets):
        return "#35f2a7"  # monochrome art falls back to the site accent
    hue = (buckets.index(max(buckets)) + .5) / 24
    r, g, b = colorsys.hls_to_rgb(hue, .64, .78)
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def main():
    projects = json.loads((ROOT / "tools" / "projects.src.json").read_text(encoding="utf-8"))
    for p in projects:
        local = []
        for i, f in enumerate(p["imgs"], 1):
            src = fetch(CDN + f, f"{p['slug']}-{i:02d}")
            # "splitV": 1-based source images that are two screenshots stacked vertically -> two gallery images
            parts = halves(src) if i in p.get("splitV", []) else [src]
            for part in parts:
                base = f"assets/img/{p['slug']}/{len(local) + 1:02d}"
                webp(part, SITE / f"{base}.webp", 1920)
                webp(part, SITE / f"{base}-sm.webp", 900, 75)
                local.append(base)
        p.pop("splitV", None)
        p["imgs"] = local
        p["tint"] = tint(SITE / f"{local[0]}-sm.webp")
        print("ok", p["slug"], len(local), p["tint"], file=sys.stderr)
    for name, url in EXTRA.items():
        src = fetch(url, name)
        if name.startswith("logo"):
            logo(src, SITE / f"assets/img/{name}.webp")
        else:
            webp(src, SITE / f"assets/img/{name}.webp", 1100, 74)
    out = SITE / "assets" / "js" / "data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by tools/build_assets.py – edit tools/projects.src.json instead.\n"
                   "window.PROJECTS = " + json.dumps(projects, ensure_ascii=False, indent=1) + ";\n",
                   encoding="utf-8")


if __name__ == "__main__":
    main()
